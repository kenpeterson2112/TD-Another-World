#!/usr/bin/env node
// Bundles src/ and data/ into one self-contained index.html, so the game
// runs by opening the file directly (desktop or phone) or from GitHub Pages,
// with no server. No dependencies; needs Node 16+.
//
//   node tools/build.js           write index.html
//   node tools/build.js --check   exit 1 if index.html is out of date
'use strict';
const fs = require('fs');
const path = require('path');
const { loadData } = require('../tests/loadData.js');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'index.html');
// Order matters: each script uses the ones before it.
const SCRIPTS = ['hex.js', 'sim.js', 'render.js', 'ui.js'];

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

// Make text safe to inline inside a <script> element.
function scriptSafe(text) {
  return text.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
}

function build() {
  const data = loadData();
  const dataJs = 'window.TD = window.TD || {};\nwindow.TD.DATA = ' + JSON.stringify(data, null, 1) + ';';
  const scripts = SCRIPTS.map((f) => `// ---- src/${f} ----\n` + read(path.join(SRC, f))).join('\n');
  const notice = '<!-- GENERATED by tools/build.js from src/ and data/. Do not edit by hand: edit the sources and rebuild. -->';

  let html = read(path.join(SRC, 'index.template.html'));
  const replace = (marker, value) => {
    if (!html.includes(marker)) throw new Error('template is missing ' + marker);
    html = html.split(marker).join(value);
  };
  replace('<!-- BUILD:NOTICE -->', notice);
  replace('/* BUILD:STYLE */', read(path.join(SRC, 'style.css')));
  replace('/* BUILD:DATA */', scriptSafe(dataJs));
  replace('/* BUILD:SCRIPTS */', scriptSafe(scripts));
  return html;
}

module.exports = { build, OUT };

if (require.main === module) {
  const html = build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? read(OUT) : '';
    if (current !== html) {
      console.error('index.html is out of date. Run: node tools/build.js');
      process.exit(1);
    }
    console.log('index.html is up to date.');
  } else {
    fs.writeFileSync(OUT, html);
    console.log(`Wrote index.html (${(html.length / 1024).toFixed(1)} KB)`);
  }
}
